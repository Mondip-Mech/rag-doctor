import { useState } from 'react'
import './DiagnosticForm.css'

function createChunk(number) {
    const chunkId = `chunk-${String(number).padStart(3, '0')}`

    return {
        localId: chunkId,
        chunk_id: chunkId,
        content: '',
        score: '',
        rank: String(number),
        source: '',
    }
}

function DiagnosticForm({ onSubmit, isLoading = false }) {
    // Main diagnostic inputs
    const [query, setQuery] = useState('')
    const [generatedAnswer, setGeneratedAnswer] = useState('')
    const [expectedAnswer, setExpectedAnswer] = useState('')
    const [assembledContext, setAssembledContext] = useState('')

    // Retrieved document chunks
    const [chunks, setChunks] = useState([])
    const [nextChunkNumber, setNextChunkNumber] = useState(1)

    // Local validation message
    const [formError, setFormError] = useState('')

    function addChunk() {
        setChunks((current) => [
            ...current,
            createChunk(nextChunkNumber),
        ])

        setNextChunkNumber((current) => current + 1)
    }

    function removeChunk(localId) {
        setChunks((current) =>
            current.filter((chunk) => chunk.localId !== localId),
        )
    }

    function updateChunk(localId, field, value) {
        setChunks((current) =>
            current.map((chunk) =>
                chunk.localId === localId
                    ? { ...chunk, [field]: value }
                    : chunk,
            ),
        )
    }

    function handleSubmit(event) {
        event.preventDefault()
        setFormError('')

        const chunkIds = chunks.map((chunk) => chunk.chunk_id.trim())

        if (new Set(chunkIds).size !== chunkIds.length) {
            setFormError('Each retrieved chunk must have a unique chunk ID.')
            return
        }

        const payload = {
            query: query.trim(),
            generated_answer: generatedAnswer.trim(),
            expected_answer: expectedAnswer.trim() || null,

            retrieved_chunks: chunks.map((chunk) => ({
                chunk_id: chunk.chunk_id.trim(),
                content: chunk.content.trim(),
                score: chunk.score === '' ? null : Number(chunk.score),
                rank: chunk.rank === '' ? null : Number(chunk.rank),
                source: chunk.source.trim() || null,
                metadata: {},
            })),

            assembled_context: assembledContext.trim() || null,
        }

        onSubmit(payload)
    }

    return (
        <section className="diagnostic-form-panel">
            <div className="diagnostic-form-heading">
                <div>
                    <span className="eyebrow">DIAGNOSTIC INPUT</span>
                    <h2>Analyze your RAG pipeline</h2>
                    <p>
                        Provide the original question, generated answer
                        and retrieved evidence.
                    </p>
                </div>

                <span className="section-tag">INPUT / 01</span>
            </div>

            <form onSubmit={handleSubmit}>
                <fieldset disabled={isLoading}>
                    <div className="form-field">
                        <label htmlFor="diagnostic-query">
                            User query <span className="required-mark">*</span>
                        </label>

                        <textarea
                            id="diagnostic-query"
                            value={query}
                            onChange={(event) => setQuery(event.target.value)}
                            placeholder="What question did the user ask?"
                            maxLength={10000}
                            rows={3}
                            required
                        />

                        <span className="field-hint">
                            The original question submitted to your RAG system.
                        </span>
                    </div>

                    <div className="form-field">
                        <label htmlFor="generated-answer">
                            Generated answer
                        </label>

                        <textarea
                            id="generated-answer"
                            value={generatedAnswer}
                            onChange={(event) =>
                                setGeneratedAnswer(event.target.value)
                            }
                            placeholder="Enter the answer generated by your LLM..."
                            maxLength={30000}
                            rows={4}
                        />
                    </div>

                    <div className="form-field">
                        <label htmlFor="expected-answer">
                            Expected answer
                            <span className="optional-label">OPTIONAL</span>
                        </label>

                        <textarea
                            id="expected-answer"
                            value={expectedAnswer}
                            onChange={(event) =>
                                setExpectedAnswer(event.target.value)
                            }
                            placeholder="Enter the reference answer, if available..."
                            maxLength={30000}
                            rows={3}
                        />

                        <span className="field-hint">
                            Used as additional reference information during diagnosis.
                        </span>
                    </div>

                    <div className="chunks-section">
                        <div className="chunks-heading">
                            <div>
                                <label>Retrieved document chunks</label>
                                <p>
                                    Add the documents returned by your retrieval system.
                                    You can also run a diagnostic with zero chunks.
                                </p>
                            </div>

                            <button
                                type="button"
                                className="secondary-button"
                                onClick={addChunk}
                            >
                                <span>+</span> Add chunk
                            </button>
                        </div>

                        {chunks.length === 0 ? (
                            <div className="empty-chunks">
                                <span className="empty-chunks-icon">⌁</span>
                                <strong>No retrieved chunks added</strong>
                                <span>
                                    An empty list will be submitted to test retrieval failures.
                                </span>
                            </div>
                        ) : (
                            <div className="chunk-list">
                                {chunks.map((chunk, index) => (
                                    <article className="chunk-card" key={chunk.localId}>
                                        <div className="chunk-card-heading">
                                            <div className="chunk-number">
                                                <span>{String(index + 1).padStart(2, '0')}</span>
                                                <strong>Retrieved chunk</strong>
                                            </div>

                                            <button
                                                type="button"
                                                className="remove-chunk-button"
                                                onClick={() => removeChunk(chunk.localId)}
                                                aria-label={`Remove chunk ${index + 1}`}
                                            >
                                                Remove
                                            </button>
                                        </div>

                                        <div className="chunk-fields">
                                            <div className="form-field">
                                                <label htmlFor={`${chunk.localId}-id`}>
                                                    Chunk ID
                                                </label>

                                                <input
                                                    id={`${chunk.localId}-id`}
                                                    value={chunk.chunk_id}
                                                    onChange={(event) =>
                                                        updateChunk(
                                                            chunk.localId,
                                                            'chunk_id',
                                                            event.target.value,
                                                        )
                                                    }
                                                    maxLength={200}
                                                    required
                                                />
                                            </div>

                                            <div className="form-field">
                                                <label htmlFor={`${chunk.localId}-source`}>
                                                    Source
                                                </label>

                                                <input
                                                    id={`${chunk.localId}-source`}
                                                    value={chunk.source}
                                                    onChange={(event) =>
                                                        updateChunk(
                                                            chunk.localId,
                                                            'source',
                                                            event.target.value,
                                                        )
                                                    }
                                                    placeholder="document.pdf"
                                                />
                                            </div>

                                            <div className="form-field">
                                                <label htmlFor={`${chunk.localId}-score`}>
                                                    Relevance score
                                                </label>

                                                <input
                                                    id={`${chunk.localId}-score`}
                                                    type="number"
                                                    value={chunk.score}
                                                    onChange={(event) =>
                                                        updateChunk(
                                                            chunk.localId,
                                                            'score',
                                                            event.target.value,
                                                        )
                                                    }
                                                    placeholder="0.95"
                                                    min="0"
                                                    max="1"
                                                    step="0.01"
                                                />

                                                <span className="field-hint">
                                                    Between 0 and 1.
                                                </span>
                                            </div>

                                            <div className="form-field">
                                                <label htmlFor={`${chunk.localId}-rank`}>
                                                    Retrieval rank
                                                </label>

                                                <input
                                                    id={`${chunk.localId}-rank`}
                                                    type="number"
                                                    value={chunk.rank}
                                                    onChange={(event) =>
                                                        updateChunk(
                                                            chunk.localId,
                                                            'rank',
                                                            event.target.value,
                                                        )
                                                    }
                                                    min="1"
                                                    step="1"
                                                />
                                            </div>
                                        </div>

                                        <div className="form-field">
                                            <label htmlFor={`${chunk.localId}-content`}>
                                                Document content
                                            </label>

                                            <textarea
                                                id={`${chunk.localId}-content`}
                                                value={chunk.content}
                                                onChange={(event) =>
                                                    updateChunk(
                                                        chunk.localId,
                                                        'content',
                                                        event.target.value,
                                                    )
                                                }
                                                placeholder="Paste the retrieved document content..."
                                                maxLength={20000}
                                                rows={4}
                                                required
                                            />
                                        </div>
                                    </article>
                                ))}
                            </div>
                        )}
                    </div>

                    <div className="form-field">
                        <label htmlFor="assembled-context">
                            Assembled context
                            <span className="optional-label">OPTIONAL</span>
                        </label>

                        <textarea
                            id="assembled-context"
                            value={assembledContext}
                            onChange={(event) =>
                                setAssembledContext(event.target.value)
                            }
                            placeholder="Enter the final combined context passed to the LLM..."
                            maxLength={100000}
                            rows={4}
                        />
                    </div>

                    {formError && (
                        <div className="form-error" role="alert">
                            {formError}
                        </div>
                    )}

                    <div className="form-footer">
                        <span className="form-footer-hint">
                            * Required field
                        </span>

                        <button
                            type="submit"
                            className="primary-button"
                            disabled={isLoading}
                        >
                            {isLoading ? (
                                <>
                                    <span className="button-spinner" />
                                    Running diagnostic...
                                </>
                            ) : (
                                <>
                                    <span>⌁</span>
                                    Run diagnostic
                                </>
                            )}
                        </button>
                    </div>
                </fieldset>
            </form>
        </section>
    )
}

export default DiagnosticForm